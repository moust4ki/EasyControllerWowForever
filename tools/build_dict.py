"""Build Dict_<locale>.lua from a word frequency list.

Default source: hermitdave/FrequencyWords (OpenSubtitles 2018, CC-BY-SA-4.0),
a list of "word count" lines sorted by frequency.

Usage:
    python tools/build_dict.py fr            # downloads fr_50k.txt -> Dict_frFR.lua
    python tools/build_dict.py en            # downloads en_50k.txt -> Dict_enUS.lua
    python tools/build_dict.py de|es|it      # German, Spanish, Italian
    python tools/build_dict.py ru            # Russian (two downloads, see WORDS)
    python tools/build_dict.py fr --input my_list.txt --size 15000
    python tools/build_dict.py ru --words russian.txt   # a local copy of the word list
"""
import argparse
import re
import urllib.request
from pathlib import Path

SOURCE = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/{lang}/{lang}_50k.txt"
LOCALES = {"fr": "frFR", "en": "enUS", "de": "deDE", "es": "esES", "it": "itIT", "ru": "ruRU"}
LETTERS = "a-zàâäáçéèêëîïíìôöóòùûüúÿñœæß"
CYRILLIC = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
WORD = re.compile(rf"^[{LETTERS}]+(['-][{LETTERS}]+)*$")
# Real one-letter words; other single letters are noise
SINGLE = {
    "fr": {"a", "à", "y"},
    "en": {"a", "i"},
    "de": set(),
    "es": {"a", "y", "o", "e", "u"},
    "it": {"a", "e", "o", "è", "i"},
    "ru": {"а", "в", "и", "к", "о", "с", "у", "я"},
}

# Russian: the subtitle lists are full of characters' names (transcribed) and
# misprints. Past the first words, one stays only if this list of Russian
# words has it (danakt/russian-words, MIT, windows-1251), each part of a
# hyphenated one. And "еще" / "ещё" are one word, kept spelled with ё at the
# better of their two places, but for those two words apart (the list has both
# spellings of a word: the one with ё replaces the other)
WORDS = "https://raw.githubusercontent.com/danakt/russian-words/master/russian.txt"
KEEP_FIRST = 1000
HOMOGRAPHS = {"все", "небо", "падеж", "осел", "мел", "прием", "истекший", "затекший"}
ROOT = Path(__file__).resolve().parent.parent


def fetch(url):
    print(f"Downloading {url}")
    with urllib.request.urlopen(url) as r:
        return r.read()


def load(lang, input_path):
    if input_path:
        return Path(input_path).read_text(encoding="utf-8").splitlines()
    return fetch(SOURCE.format(lang=lang)).decode("utf-8").splitlines()


def load_words(path):
    data = Path(path).read_bytes() if path else fetch(WORDS)
    words = data.decode("cp1251").lower().split()
    return {w.replace("ё", "е") for w in words}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("lang", choices=sorted(LOCALES))
    ap.add_argument("--input", help="local frequency list (one 'word [count]' per line)")
    ap.add_argument("--size", type=int, default=12000)
    ap.add_argument("--words", help="local copy of the Russian word list (ru)")
    args = ap.parse_args()

    russian = args.lang == "ru"
    pattern = re.compile(rf"^[{CYRILLIC}]+(['-][{CYRILLIC}]+)*$") if russian else WORD
    known = load_words(args.words) if russian else None
    words, at = [], {}          # the words kept, and where: by their key (the word)
    seen = 0                    # words the list gives, the ones kept or not
    for line in load(args.lang, args.input):
        parts = line.split()
        if not parts:
            continue
        w = parts[0].lower()
        if w in at or not pattern.match(w):
            continue
        if len(w) == 1 and w not in SINGLE[args.lang]:
            continue
        seen += 1
        key = w.replace("ё", "е")      # (a word: whichever of its two spellings)
        if known and seen > KEEP_FIRST and not all(p in known for p in re.split("['-]", key)):
            continue
        if russian and key in HOMOGRAPHS:
            key = w
        if key in at:
            if "ё" in w:
                words[at[key]] = w   # the spelling with ё, where the other one was
            continue
        at[key] = len(words)
        words.append(w)
        if len(words) >= args.size:
            break

    locale = LOCALES[args.lang]
    lines, line = [], ""
    for w in words:
        if len(line) + len(w) + 1 > 100:
            lines.append(line)
            line = ""
        line = f"{line} {w}" if line else w
    if line:
        lines.append(line)

    out = ROOT / f"Dict_{locale}.lua"
    body = "\n".join(lines)
    kept = (f"-- Kept when the Russian word list of danakt (danakt/russian-words, MIT) has them,\n"
            f"-- past the first {KEEP_FIRST}; a word spelled both with е and ё: with ё\n") if russian else ""
    out.write_text(
        "local _, CK = ...\n"
        "CK.Dicts = CK.Dicts or {}\n\n"
        f"-- {len(words)} words sorted by frequency. Generated by tools/build_dict.py\n"
        "-- Source: FrequencyWords (hermitdave), OpenSubtitles 2018, CC-BY-SA-4.0\n"
        f"{kept}"
        f"CK.Dicts.{locale} = [[\n{body}\n]]\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(words)} words to {out.name}")


if __name__ == "__main__":
    main()
